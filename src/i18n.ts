let current: Lang = "en";
const listeners = new Set<() => void>();

export function setLang(l: Lang): void {
  if (l === current) return;
  current = l;
  listeners.forEach((f) => f());
}

export function getLang(): Lang {
  return current;
}

export function onLang(fn: () => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function t(s: string): string {
  return current === "uk" ? UK[s] ?? s : s;
}

export function applyI18n(scope: ParentNode): void {
  scope.querySelectorAll("[data-i18n]").forEach((n) => {
    n.textContent = t(n.getAttribute("data-i18n")!);
  });
  scope.querySelectorAll("[data-i18n-ph]").forEach((n) => {
    (n as HTMLInputElement).placeholder = t(n.getAttribute("data-i18n-ph")!);
  });
  scope.querySelectorAll("[data-i18n-title]").forEach((n) => {
    (n as HTMLElement).title = t(n.getAttribute("data-i18n-title")!);
  });
}
